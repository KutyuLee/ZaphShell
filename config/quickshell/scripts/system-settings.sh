#!/usr/bin/env python3
import json
import os
import re
import subprocess
import sys

HYPR_LUA = os.path.expanduser("~/.config/hypr/hyprland.lua")
HYPR_CONF = os.path.expanduser("~/.config/hypr/hyprland.conf")
CHROMA_CONF = os.path.expanduser("~/.config/hypr/chromashell-overrides.conf")
CHROMA_STATE = os.path.expanduser("~/.cache/quickshell/hypr-overrides.json")


def is_lua_mode():
    return os.path.isfile(HYPR_LUA)


def run_json(cmd):
    try:
        out = subprocess.check_output(cmd, text=True, stderr=subprocess.DEVNULL, timeout=2.0)
        return json.loads(out)
    except Exception:
        return None


def get_hypr_opt(opt, fallback):
    data = run_json(["hyprctl", "getoption", opt, "-j"])
    if not isinstance(data, dict):
        return fallback
    for k in ("str", "float", "int"):
        if k in data and data[k] is not None:
            return data[k]
    return fallback


def load_conf_overrides():
    try:
        with open(CHROMA_STATE, "r", encoding="utf-8") as f:
            obj = json.load(f)
            if isinstance(obj, dict):
                return obj
    except Exception:
        pass
    return {"monitors": {}, "keyboard": {}, "input": {}}


def write_conf_overrides(obj):
    os.makedirs(os.path.dirname(CHROMA_STATE), exist_ok=True)
    with open(CHROMA_STATE, "w", encoding="utf-8") as f:
        json.dump(obj, f, indent=2)

    lines = ["# Auto-generated by ChromaShell Settings — do not edit manually", ""]
    mons = obj.get("monitors", {})
    for m_name, m_cfg in mons.items():
        if m_cfg.get("disabled", False):
            lines.append(f"monitor = {m_name}, disable")
            continue
        mode = m_cfg.get("mode", "preferred")
        pos = m_cfg.get("position", "auto")
        scale = m_cfg.get("scale", "1")
        extras = []
        tf = int(m_cfg.get("transform", 0) or 0)
        if tf != 0:
            extras.append(f"transform, {tf}")
        vrr = int(m_cfg.get("vrr", 0) or 0)
        if vrr != 0:
            extras.append(f"vrr, {vrr}")
        bd = int(m_cfg.get("bitdepth", 8) or 8)
        if bd == 10:
            extras.append("bitdepth, 10")
        cm = str(m_cfg.get("cm", "") or "").strip()
        if cm and cm != "auto":
            extras.append(f"cm, {cm}")
        mirror = str(m_cfg.get("mirror", "") or "").strip()
        if mirror:
            extras.append(f"mirror, {mirror}")
        suffix = (", " + ", ".join(extras)) if extras else ""
        lines.append(f"monitor = {m_name}, {mode}, {pos}, {scale}{suffix}")
    if mons:
        lines.append("")

    kb = obj.get("keyboard", {})
    inp = obj.get("input", {})
    if kb or inp:
        lines.append("input {")
        if "layout" in kb:
            lines.append(f"    kb_layout = {kb['layout']}")
        if "variant" in kb:
            lines.append(f"    kb_variant = {kb['variant']}")
        if "options" in kb:
            lines.append(f"    kb_options = {kb['options']}")
        if "sensitivity" in inp:
            lines.append(f"    sensitivity = {inp['sensitivity']}")
        if "naturalScroll" in inp:
            lines.append(f"    natural_scroll = {'true' if inp['naturalScroll'] else 'false'}")
        lines.append("}")
        lines.append("")

    os.makedirs(os.path.dirname(CHROMA_CONF), exist_ok=True)
    with open(CHROMA_CONF, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    if os.path.isfile(HYPR_CONF):
        try:
            with open(HYPR_CONF, "r", encoding="utf-8") as f:
                hc = f.read()
            if "chromashell-overrides.conf" not in hc:
                with open(HYPR_CONF, "a", encoding="utf-8") as f:
                    f.write("\n# ChromaShell Settings Overrides\nsource = ~/.config/hypr/chromashell-overrides.conf\n")
        except Exception:
            pass

    subprocess.run(["hyprctl", "reload"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=3.0)


def read_hypr_lua():
    try:
        with open(HYPR_LUA, "r", encoding="utf-8") as f:
            return f.read()
    except Exception:
        return ""


def write_hypr_lua(content):
    with open(HYPR_LUA, "w", encoding="utf-8") as f:
        f.write(content)
    subprocess.run(["hyprctl", "reload"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=3.0)


def extract_lua_str(text, key, default=""):
    m = re.search(rf'\b{re.escape(key)}\s*=\s*"([^"]*)"', text)
    return m.group(1) if m else default


def extract_lua_num(text, key, default=0.0):
    m = re.search(rf'\b{re.escape(key)}\s*=\s*(-?\d+(?:\.\d+)?)', text)
    try:
        return float(m.group(1)) if m else default
    except Exception:
        return default


def extract_lua_bool(text, key, default=False):
    m = re.search(rf'\b{re.escape(key)}\s*=\s*(true|false)', text)
    if not m:
        return default
    return m.group(1) == "true"


def replace_lua_str(text, key, val):
    escaped = val.replace("\\", "\\\\").replace('"', '\\"')
    pat = rf'(\b{re.escape(key)}\s*=\s*)"[^"]*"'
    if re.search(pat, text):
        return re.sub(pat, rf'\1"{escaped}"', text, count=1)
    return text


def replace_lua_raw(text, key, raw_val):
    pat = rf'(\b{re.escape(key)}\s*=\s*)(?:-?\d+(?:\.\d+)?|true|false)'
    if re.search(pat, text):
        return re.sub(pat, rf'\1{raw_val}', text, count=1)
    return text


def _parse_lua_monitor_opts(lua, name):
    m_blk = re.search(rf'hl\.monitor\(\{{\s*output\s*=\s*"{re.escape(name)}"([^}}]*)\}}\)', lua, re.MULTILINE)
    if not m_blk:
        return {}
    b = m_blk.group(1)
    return {
        "mode": extract_lua_str(b, "mode", ""),
        "position": extract_lua_str(b, "position", ""),
        "scale": extract_lua_str(b, "scale", ""),
        "transform": int(extract_lua_num(b, "transform", 0)),
        "vrr": int(extract_lua_num(b, "vrr", 0)),
        "bitdepth": int(extract_lua_num(b, "bitdepth", 8)),
        "cm": extract_lua_str(b, "cm", ""),
        "mirror": extract_lua_str(b, "mirror", ""),
        "disabled": extract_lua_bool(b, "disabled", False),
    }


def upsert_lua_kb_str(text, key, val):
    escaped = val.replace("\\", "\\\\").replace('"', '\\"')
    pat = rf'(\b{re.escape(key)}\s*=\s*)"[^"]*"'
    if re.search(pat, text):
        return re.sub(pat, rf'\1"{escaped}"', text, count=1)
    m = re.search(r'(input\s*=\s*\{\s*\n)', text)
    if m:
        ins = m.end(1)
        return text[:ins] + f'        {key} = "{escaped}",\n' + text[ins:]
    return text


def get_xkb_catalog():
    layouts = []
    variants = {}
    lst_path = "/usr/share/X11/xkb/rules/evdev.lst"
    if os.path.isfile(lst_path):
        try:
            section = None
            with open(lst_path, "r", encoding="utf-8", errors="replace") as f:
                for raw in f:
                    line = raw.rstrip("\r\n")
                    if line.startswith("! "):
                        section = line[2:].strip()
                        continue
                    if not line.strip() or section not in ("layout", "variant"):
                        continue
                    m = re.match(r'^\s+([^\s]+)\s+(.+?)\s*$', line)
                    if not m:
                        continue
                    code, desc = m.group(1), m.group(2)
                    if section == "layout":
                        layouts.append({"code": code, "name": desc})
                    elif section == "variant":
                        if ": " in desc:
                            lay_code, v_desc = desc.split(": ", 1)
                            lay_code = lay_code.strip()
                            variants.setdefault(lay_code, []).append({"code": code, "name": v_desc.strip()})
        except Exception:
            pass
    if not layouts:
        layouts = [
            {"code": "us", "name": "English (US)"},
            {"code": "gb", "name": "English (UK)"},
            {"code": "hu", "name": "Hungarian"},
            {"code": "de", "name": "German"},
            {"code": "fr", "name": "French"},
            {"code": "es", "name": "Spanish"},
            {"code": "it", "name": "Italian"},
            {"code": "pt", "name": "Portuguese"},
            {"code": "pl", "name": "Polish"},
            {"code": "ru", "name": "Russian"},
            {"code": "jp", "name": "Japanese"},
            {"code": "kr", "name": "Korean"},
        ]
    layouts.sort(key=lambda x: x["name"].lower())
    for k in variants:
        variants[k].sort(key=lambda x: x["name"].lower())
    return {"layouts": layouts, "variants": variants}


def _mode_sort_key(mode_str):
    m = re.match(r'^(\d+)x(\d+)@([0-9.]+)', mode_str)
    if not m:
        return (0, 0.0)
    return (int(m.group(1)) * int(m.group(2)), float(m.group(3)))


def get_info(include_catalog=False):
    lua_mode = is_lua_mode()
    lua = read_hypr_lua() if lua_mode else ""
    ov = load_conf_overrides() if not lua_mode else {}
    mons_ov = ov.get("monitors", {}) if not lua_mode else {}
    mons_raw = run_json(["hyprctl", "monitors", "all", "-j"])
    if not isinstance(mons_raw, list):
        mons_raw = run_json(["hyprctl", "monitors", "-j"]) or []
    devs_raw = run_json(["hyprctl", "devices", "-j"]) or {}

    monitors = []
    for m in mons_raw:
        m_name = m.get("name", "")
        modes = []
        seen_modes = set()
        for am in m.get("availableModes", []):
            clean = str(am).strip()
            if clean and clean not in seen_modes:
                seen_modes.add(clean)
                modes.append(clean)
        modes.sort(key=_mode_sort_key, reverse=True)

        cfg_opts = _parse_lua_monitor_opts(lua, m_name) if lua_mode else mons_ov.get(m_name, {})
        cur_fmt = str(m.get("currentFormat", "XRGB8888"))
        live_bd = 10 if ("2101010" in cur_fmt or "161616" in cur_fmt) else 8
        live_cm = str(m.get("colorManagementPreset", "srgb") or "srgb")
        live_mirror = str(m.get("mirrorOf", "none") or "none")
        if live_mirror == "none":
            live_mirror = ""
        hw = m.get("hardwareDetails") or {}

        cfg_vrr = cfg_opts.get("vrr")
        if cfg_vrr is None:
            cfg_vrr = 1 if m.get("vrr", False) else 0

        monitors.append({
            "name": m_name,
            "description": m.get("description", ""),
            "width": m.get("width", 1920),
            "height": m.get("height", 1080),
            "refreshRate": round(float(m.get("refreshRate", 60.0)), 2),
            "x": m.get("x", 0),
            "y": m.get("y", 0),
            "scale": round(float(m.get("scale", 1.0)), 2),
            "transform": int(m.get("transform", cfg_opts.get("transform", 0)) or 0),
            "vrr": int(cfg_vrr or 0),
            "bitdepth": int(cfg_opts.get("bitdepth", live_bd) or live_bd),
            "cm": str(cfg_opts.get("cm") or live_cm or "srgb"),
            "mirror": str(cfg_opts.get("mirror") if "mirror" in cfg_opts else live_mirror),
            "disabled": bool(m.get("disabled", cfg_opts.get("disabled", False))),
            "supportsHdr": bool(hw.get("hdr", False)),
            "focused": bool(m.get("focused", False)),
            "activeWorkspace": (m.get("activeWorkspace") or {}).get("id", 1),
            "availableModes": modes,
        })

    active_layout = "English (US)"
    for kb in devs_raw.get("keyboards", []):
        if kb.get("main"):
            active_layout = kb.get("active_keymap", active_layout)
            break

    if lua_mode:
        kb_info = {
            "layout": extract_lua_str(lua, "kb_layout", "us"),
            "variant": extract_lua_str(lua, "kb_variant", ""),
            "options": extract_lua_str(lua, "kb_options", ""),
            "activeLayout": active_layout,
        }
        input_info = {
            "sensitivity": extract_lua_num(lua, "sensitivity", 0.0),
            "naturalScroll": extract_lua_bool(lua, "natural_scroll", False),
        }
    else:
        ov = load_conf_overrides()
        kb_ov = ov.get("keyboard", {})
        inp_ov = ov.get("input", {})
        kb_info = {
            "layout": str(kb_ov.get("layout", get_hypr_opt("input:kb_layout", "us")) or "us"),
            "variant": str(kb_ov.get("variant", get_hypr_opt("input:kb_variant", "")) or ""),
            "options": str(kb_ov.get("options", get_hypr_opt("input:kb_options", "")) or ""),
            "activeLayout": active_layout,
        }
        try:
            sens_val = float(inp_ov.get("sensitivity", get_hypr_opt("input:sensitivity", 0.0)))
        except Exception:
            sens_val = 0.0
        nat_raw = inp_ov.get("naturalScroll", bool(get_hypr_opt("input:natural_scroll", 0)))
        input_info = {
            "sensitivity": round(sens_val, 2),
            "naturalScroll": bool(nat_raw),
        }

    info = {
        "monitors": monitors,
        "keyboard": kb_info,
        "input": input_info,
    }
    if include_catalog:
        info["xkbCatalog"] = get_xkb_catalog()
    print(json.dumps(info))


def set_keyboard(layout, variant, options):
    if is_lua_mode():
        lua = read_hypr_lua()
        if not lua:
            get_info()
            return
        lua = upsert_lua_kb_str(lua, "kb_layout", layout)
        lua = upsert_lua_kb_str(lua, "kb_variant", variant)
        lua = upsert_lua_kb_str(lua, "kb_options", options)
        write_hypr_lua(lua)
    else:
        ov = load_conf_overrides()
        ov.setdefault("keyboard", {})
        ov["keyboard"]["layout"] = layout
        ov["keyboard"]["variant"] = variant
        ov["keyboard"]["options"] = options
        write_conf_overrides(ov)
    subprocess.run(["hyprctl", "switchxkblayout", "all", "0"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=2.0)
    get_info()


def set_input(sensitivity, natural_scroll):
    try:
        sens_val = max(-1.0, min(1.0, round(float(sensitivity), 2)))
    except Exception:
        sens_val = 0.0
    nat_bool = str(natural_scroll).lower() in ("true", "1", "yes")
    if is_lua_mode():
        lua = read_hypr_lua()
        if not lua:
            get_info()
            return
        nat_str = "true" if nat_bool else "false"
        input_idx = lua.find("input = {")
        if input_idx != -1:
            end_idx = lua.find("})", input_idx)
            if end_idx != -1:
                block = lua[input_idx:end_idx]
                block = replace_lua_raw(block, "sensitivity", str(sens_val))
                block = replace_lua_raw(block, "natural_scroll", nat_str)
                lua = lua[:input_idx] + block + lua[end_idx:]
        write_hypr_lua(lua)
    else:
        ov = load_conf_overrides()
        ov.setdefault("input", {})
        ov["input"]["sensitivity"] = sens_val
        ov["input"]["naturalScroll"] = nat_bool
        write_conf_overrides(ov)
    get_info()


def upsert_monitor_block(lua, cfg):
    name = cfg["name"]
    pattern = re.compile(
        rf'\nhl\.monitor\(\{{\s*output\s*=\s*"{re.escape(name)}"[^}}]*\}}\)\n?',
        re.MULTILINE,
    )
    fields = [f'    output    = "{name}",']
    if cfg.get("disabled", False):
        fields.append('    disabled  = true,')
    else:
        fields.append(f'    mode      = "{cfg.get("mode", "preferred")}",')
        fields.append(f'    position  = "{cfg.get("position", "auto")}",')
        fields.append(f'    scale     = "{cfg.get("scale", "1")}",')
        tf = int(cfg.get("transform", 0) or 0)
        if tf != 0:
            fields.append(f'    transform = {tf},')
        vrr = int(cfg.get("vrr", 0) or 0)
        if vrr != 0:
            fields.append(f'    vrr       = {vrr},')
        bd = int(cfg.get("bitdepth", 8) or 8)
        if bd == 10:
            fields.append(f'    bitdepth  = 10,')
        cm = str(cfg.get("cm", "") or "").strip()
        if cm and cm not in ("srgb", "auto"):
            fields.append(f'    cm        = "{cm}",')
        mirror = str(cfg.get("mirror", "") or "").strip()
        if mirror:
            fields.append(f'    mirror    = "{mirror}",')

    new_block = "\nhl.monitor({\n" + "\n".join(fields) + "\n})\n"
    if pattern.search(lua):
        return pattern.sub(new_block, lua, count=1)
    anchor = "---- MY PROGRAMS ----"
    idx = lua.find(anchor)
    if idx != -1:
        line_start = lua.rfind("\n", 0, max(0, idx - 22))
        ins = line_start if line_start != -1 else idx
        return lua[:ins] + "\n" + new_block + lua[ins:]
    return lua + "\n" + new_block


def _existing_monitor_cfg(name, mons_raw, lua, mons_ov):
    cur = mons_raw.get(name, {})
    prev = _parse_lua_monitor_opts(lua, name) if lua else mons_ov.get(name, {})
    cur_mode = f"{cur.get('width', 1920)}x{cur.get('height', 1080)}@{float(cur.get('refreshRate', 60.0)):.2f}Hz" if cur else "preferred"
    cur_pos = f"{cur.get('x', 0)}x{cur.get('y', 0)}" if cur else "auto"
    cur_fmt = str(cur.get("currentFormat", "XRGB8888"))
    cur_bd = 10 if ("2101010" in cur_fmt or "161616" in cur_fmt) else 8
    cur_mirror = str(cur.get("mirrorOf", "none") or "none")
    if cur_mirror == "none":
        cur_mirror = ""
    return {
        "name": name,
        "mode": prev.get("mode") or cur_mode,
        "position": prev.get("position") or cur_pos,
        "scale": str(prev.get("scale") or cur.get("scale", 1)),
        "transform": int(prev.get("transform", cur.get("transform", 0)) or 0),
        "vrr": int(prev.get("vrr") if prev.get("vrr") is not None else (1 if cur.get("vrr", False) else 0)),
        "bitdepth": int(prev.get("bitdepth", cur_bd) or cur_bd),
        "cm": str(prev.get("cm") or cur.get("colorManagementPreset", "srgb") or "srgb"),
        "mirror": str(prev.get("mirror") if "mirror" in prev else cur_mirror),
        "disabled": bool(prev.get("disabled", cur.get("disabled", False))),
    }


def apply_monitor_cfg(cfg):
    name = str(cfg.get("name", ""))
    if not name:
        get_info()
        return
    mons_all = run_json(["hyprctl", "monitors", "all", "-j"])
    if not isinstance(mons_all, list):
        mons_all = run_json(["hyprctl", "monitors", "-j"]) or []
    mons_raw = {m.get("name"): m for m in mons_all}
    layout_items = cfg.get("layout") or []

    if not is_lua_mode():
        ov = load_conf_overrides()
        mons_ov = ov.setdefault("monitors", {})
        for it in layout_items:
            it_name = str(it.get("name", ""))
            if not it_name or it_name == name:
                continue
            base = _existing_monitor_cfg(it_name, mons_raw, "", mons_ov)
            base["position"] = f"{int(round(float(it.get('x', 0))))}x{int(round(float(it.get('y', 0))))}"
            mons_ov[it_name] = base
        mons_ov[name] = {
            "mode": str(cfg.get("mode", "preferred")),
            "position": str(cfg.get("position", "auto")),
            "scale": str(cfg.get("scale", "1")),
            "transform": int(cfg.get("transform", 0) or 0),
            "vrr": int(cfg.get("vrr", 0) or 0),
            "bitdepth": int(cfg.get("bitdepth", 8) or 8),
            "cm": str(cfg.get("cm", "srgb") or "srgb"),
            "mirror": str(cfg.get("mirror", "") or ""),
            "disabled": bool(cfg.get("disabled", False)),
        }
        write_conf_overrides(ov)
        get_info()
        return

    lua = read_hypr_lua()
    if not lua:
        get_info()
        return
    for it in layout_items:
        it_name = str(it.get("name", ""))
        if not it_name or it_name == name:
            continue
        base = _existing_monitor_cfg(it_name, mons_raw, lua, {})
        base["position"] = f"{int(round(float(it.get('x', 0))))}x{int(round(float(it.get('y', 0))))}"
        lua = upsert_monitor_block(lua, base)
    lua = upsert_monitor_block(lua, cfg)
    write_hypr_lua(lua)
    get_info()


def set_monitor(name, mode, position, scale, layout_json=""):
    layout = []
